-- Creates the donors table. Flyway runs this once per database and records it,
-- so later changes go in new files (V2__..., V3__...), never by editing this one.

CREATE TABLE donors (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name          VARCHAR(100) NOT NULL,
    age                INTEGER      NOT NULL,
    gender             VARCHAR(10)  NOT NULL,
    blood_group        VARCHAR(3)   NOT NULL,
    phone              VARCHAR(10)  NOT NULL,
    email              VARCHAR(120),
    city               VARCHAR(60)  NOT NULL,
    last_donation_date DATE,
    available          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMP    NOT NULL,
    updated_at         TIMESTAMP    NOT NULL,

    CONSTRAINT uk_donors_phone UNIQUE (phone),
    CONSTRAINT ck_donors_age CHECK (age BETWEEN 18 AND 65),
    CONSTRAINT ck_donors_blood_group CHECK (blood_group IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-'))
);

-- Searches filter by blood group, so index it
CREATE INDEX idx_donors_blood_group ON donors (blood_group);
